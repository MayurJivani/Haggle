// RealTime wire format, shared with apps/web (type-only import). Units as in ledger.ts, sent as numbers:
// prices in 1/10,000 of the instrument currency, quantities in micro-shares, money in euro cents.

import type { ExchangeId, ExchangeStatus, MarketState } from './calendar.js';

export type { ExchangeId, ExchangeStatus, MarketState };

export type Kind = 'stock' | 'etf' | 'index' | 'adr' | 'reit' | 'fund';

export interface Instrument {
  id: number;
  symbol: string;
  mic: string;
  exchange: ExchangeId;
  name: string;
  kind: Kind;
  currency: string;
  country: string | null;
  sector: string | null;
  industry: string | null;
  marketCapUsd: number | null;
  logoUrl: string | null;
  isin: string | null;
  status: 'active' | 'halted' | 'delisted';
}

/**
 * realtime: from the exchange as it happens. delayed: the feed is behind by `delayMin`.
 * eod: an end-of-day figure. dev: generated by the development adapter, never real.
 */
export type Quality = 'realtime' | 'delayed' | 'eod' | 'dev';

export interface Quote {
  id: number;
  last: number | null;
  bid: number | null;
  ask: number | null;
  /** Shares at the bid and ask, when the feed reports them. */
  bidSize: number | null;
  askSize: number | null;
  open: number | null;
  high: number | null;
  low: number | null;
  prevClose: number | null;
  volume: number | null;
  /** Epoch ms of the latest trade or quote this reflects, as stamped by the source. */
  at: number;
  quality: Quality;
  delayMin: number;
  source: string;
  halted?: boolean;
}

/** What the screen should say about a price: its quality, or that it is old or the market shut. */
export type PriceStatus = Quality | 'stale' | 'closed' | 'none';

export interface Candle {
  /** Epoch ms of the bar's start. */
  t: number;
  o: number;
  h: number;
  l: number;
  c: number;
  v: number;
}

export type ChartRange = '1D' | '5D' | '1M' | '3M' | '6M' | '1Y' | '5Y' | 'MAX';

export interface History {
  id: number;
  range: ChartRange;
  resolution: string;
  candles: Candle[];
  currency: string;
  source: string;
  quality: Quality;
}

export interface Details {
  instrument: Instrument;
  quote: Quote | null;
  status: ExchangeStatus;
  fiftyTwoWeek: { low: number; high: number } | null;
  /** Whether this instrument can be priced at all by the configured providers. */
  covered: boolean;
}

export interface NewsItem {
  id: string;
  headline: string;
  summary: string | null;
  url: string;
  source: string;
  at: number;
  symbols: string[];
}

export type OrderType = 'market' | 'limit';
export type OrderStatus = 'open' | 'partially_filled' | 'filled' | 'cancelled' | 'rejected';
export type RejectReason =
  | 'insufficient_cash' | 'insufficient_shares' | 'invalid_quantity' | 'invalid_price' | 'market_closed' | 'stale_quote' | 'no_quote'
  | 'delayed_quote' | 'halted' | 'delisted' | 'season_closed' | 'not_joined' | 'unknown_instrument' | 'duplicate' | 'rate_limited'
  | 'bad_request' | 'not_supported' | 'server_error';

export interface Order {
  id: string;
  clientOrderId: string;
  instrument: Pick<Instrument, 'id' | 'symbol' | 'name' | 'exchange' | 'currency'>;
  side: 'buy' | 'sell';
  type: OrderType;
  qty: number;
  filledQty: number;
  limitPrice: number | null;
  reserved: number;
  queued: boolean;
  status: OrderStatus;
  reason: string | null;
  createdAt: number;
  updatedAt: number;
}

export interface Execution {
  id: number;
  orderId: string;
  instrument: Pick<Instrument, 'id' | 'symbol' | 'name' | 'currency'>;
  side: 'buy' | 'sell';
  qty: number;
  price: number;
  fxPerEur: string;
  total: number;
  realized: number;
  quoteAt: number;
  quality: Quality;
  /** Which price the fill used: ask, bid, last plus slippage, or the limit. */
  basis: string;
  at: number;
}

export interface LedgerEntry {
  id: number;
  kind: 'grant' | 'buy' | 'sell' | 'dividend' | 'cash_in_lieu';
  amount: number;
  balanceAfter: number;
  note: string | null;
  at: number;
}

export interface PositionView {
  instrument: Pick<Instrument, 'id' | 'symbol' | 'name' | 'exchange' | 'currency' | 'status'>;
  qty: number;
  reservedQty: number;
  cost: number;
  realized: number;
  /** Mark price and the euro value at it; null when no price is known. */
  mark: number | null;
  markStatus: PriceStatus;
  value: number | null;
  unrealized: number | null;
  dayChange: number | null;
}

export interface Season {
  id: string;
  slug: string;
  name: string;
  kind: 'open' | 'weekly' | 'monthly' | 'event';
  startingCash: number;
  startsAt: number;
  endsAt: number | null;
  joinUntil: number | null;
  rules: string;
  status: 'scheduled' | 'active' | 'finished';
  players: number;
  joined: boolean;
}

export interface Portfolio {
  accountId: string;
  season: Season;
  cash: number;
  reserved: number;
  invested: number;
  value: number;
  realized: number;
  unrealized: number;
  dayPnl: number | null;
  returnBps: number;
  positions: PositionView[];
  /** Positions whose price is missing, so the value counts them at cost. */
  unpriced: number;
}

export interface BoardRow {
  rank: number;
  userId: string;
  nickname: string;
  value: number;
  returnBps: number;
  dayPnl: number | null;
  bestPick: { symbol: string; returnBps: number } | null;
  public: boolean;
}

export interface Notification {
  id: number;
  kind: string;
  text: string;
  read: boolean;
  at: number;
}

export interface Activity {
  nickname: string;
  userId: string;
  side: 'buy' | 'sell';
  symbol: string;
  instrumentId: number;
  qty: number;
  price: number;
  currency: string;
  at: number;
}

/** What the server knows about its data feeds, for the honesty line on every screen. */
export interface FeedInfo {
  providers: { id: string; label: string; exchanges: ExchangeId[]; quality: Record<string, Quality>; up: boolean; detail: string }[];
  dev: boolean;
  /** Fill rules shown to the player. */
  policy: { maxQuoteAgeSec: number; slippageBps: number; delayedFills: boolean; extendedHours: boolean; partialFills: boolean; maxSpreadBps: number };
}

// ---------------------------------------------------------------- socket

export type ClientMsg =
  | { t: 'sub'; ids: number[] }
  | { t: 'unsub'; ids: number[] };

export type ServerMsg =
  | { t: 'hello'; userId: string | null; serverNow: number }
  | { t: 'q'; q: Quote[] }
  | { t: 'order'; order: Order }
  | { t: 'fill'; execution: Execution }
  | { t: 'note'; n: Notification }
  | { t: 'feed'; feed: FeedInfo };
